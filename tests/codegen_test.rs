use tool_compile_cuda::{Node, as_elementwise, compile, emit};
use tool_compile_triton::term::{Elementwise, Expr, Lit, Operand};

fn leaf(name: &str) -> String {
    format!(r#"{{"leaf":{{"name":"{name}"}}}}"#)
}

fn elem_term(body: &str) -> String {
    format!(r#"{{"op":"store","args":[{body},{}]}}"#, leaf("out"))
}

fn parse(raw: &str) -> Node {
    serde_json::from_str(raw).expect("the test term must parse")
}

fn emit_term(body: &str) -> String {
    let e = as_elementwise(&parse(&elem_term(body))).expect("elementwise");
    emit(&e).expect("a lowered elementwise term emits")
}

#[test]
fn emits_a_real_cuda_translation_unit() {
    // silu(mul(transpose(w, 0, 1), x)) — a decoder-tail spelling
    let body = format!(
        r#"{{"op":"silu","args":[{{"op":"mul","args":[
            {{"op":"transpose","args":[{},0,1]}}, {}]}}]}}"#,
        leaf("w"),
        leaf("x")
    );
    let src = emit_term(&body);
    // it is CUDA C++, not pseudocode
    assert!(src.contains("#include <cuda_runtime.h>"));
    assert!(src.contains("template <typename T>"));
    assert!(src.contains("__global__ void elem_kernel_"));
    assert!(src.contains("<<<grid, tb, 0, stream>>>"));
    assert!(src.contains("extern \"C\" cudaError_t launch_"));
    // dtype dispatch covers all six instantiations
    for case in [
        "CUDA_EMIT_F32",
        "CUDA_EMIT_F64",
        "CUDA_EMIT_F16",
        "CUDA_EMIT_BF16",
        "CUDA_EMIT_I32",
        "CUDA_EMIT_I64",
    ] {
        assert!(src.contains(case), "missing {case}");
    }
    // the kernel is a grid-stride loop over the flat output
    assert!(src.contains("i += gstride"));
    assert!(src.contains("i < nout"));
    // flat-index decomposition matches the Triton emitter's scheme
    assert!(src.contains("c3 = i % sh3"));
    assert!(src.contains("c0 = r2 / sh1"));
    // host helpers for broadcast/strides/views are present
    for f in [
        "elem_broadcast",
        "elem_pad4",
        "elem_effective_strides",
        "elem_transpose",
        "elem_permute",
        "elem_pack_geom",
    ] {
        assert!(src.contains(f), "missing host helper {f}");
    }
    // the transpose view is documented, not silently dropped
    assert!(src.contains("transpose(0,1)"));
    // silu lowers through the sigmoid helper, mul through `*`
    assert!(src.contains("cuda_emit_detail::e_exp"));
    assert!(src.contains(" * "));
    // the module opens with the generated-by banner
    assert!(src.starts_with("// Generated by tool-compile-cuda"));
}

#[test]
fn every_pointwise_op_lowers() {
    let cases: [(&str, &str); 10] = [
        ("mul", " * "),
        ("sub", " - "),
        ("neg", "(-("),
        ("relu", "? ("),
        ("exp", "e_exp"),
        ("sigmoid", "e_exp"),
        ("tanh", "e_tanh"),
        ("gelu", "e_erf"),
        ("silu", "e_exp"),
        ("bias", " + "),
    ];
    for (op, needle) in cases {
        let args = if matches!(
            op,
            "neg" | "relu" | "exp" | "sigmoid" | "tanh" | "gelu" | "silu"
        ) {
            format!(r#"[{}]"#, leaf("a"))
        } else {
            format!(r#"[{},{}]"#, leaf("a"), leaf("b"))
        };
        let body = format!(r#"{{"op":"{op}","args":{args}}}"#);
        let src = emit_term(&body);
        assert!(src.contains(needle), "{op} did not lower ({needle})");
        assert!(src.contains("__global__"), "{op} emitted no kernel");
    }
}

#[test]
fn literals_and_pipeline_identities_lower() {
    // pipeline(depth, body) is the identity; a literal leaf expression
    // still emits a compilable kernel
    let body = format!(
        r#"{{"op":"pipeline","args":[3,{{"op":"mul","args":[{},2]}}]}}"#,
        leaf("a")
    );
    let src = emit_term(&body);
    assert!(src.contains("(W)2"), "{src}");
    assert!(src.contains(" * "));
}

#[test]
fn tile_load_and_nested_views_lower() {
    let body = format!(
        r#"{{"op":"mul","args":[
            {{"op":"tile_load","args":[{{"op":"permute","args":[{},2,0,1]}}]}},
            {{"leaf":{{"name":"b"}}}}]}}"#,
        leaf("a")
    );
    let src = emit_term(&body);
    assert!(src.contains("permute(2,0,1)"), "{src}");
    assert!(src.contains("mul"));
}

#[test]
fn kernel_and_launcher_names_are_stable_and_distinct() {
    let b1 = r#"{"op":"mul","args":[{"leaf":{"name":"a"}},{"leaf":{"name":"b"}}]}"#;
    let b2 = r#"{"op":"sub","args":[{"leaf":{"name":"a"}},{"leaf":{"name":"b"}}]}"#;
    let s1 = emit_term(b1);
    let s2 = emit_term(b2);
    let name1 = s1
        .lines()
        .find(|l| l.starts_with("extern \"C\" cudaError_t launch_"))
        .unwrap();
    let name2 = s2
        .lines()
        .find(|l| l.starts_with("extern \"C\" cudaError_t launch_"))
        .unwrap();
    assert_ne!(name1, name2);
    // determinism: same term -> same symbol
    assert_eq!(name1, {
        let s = emit_term(b1);
        s.lines()
            .find(|l| l.starts_with("extern \"C\" cudaError_t launch_"))
            .unwrap()
            .to_string()
    });
}

#[test]
fn emit_refuses_an_op_tag_it_cannot_lower() {
    // `Expr` is public, so a hand-built `Elementwise` can carry an op
    // tag `as_elementwise` would never produce — `emit` must name it,
    // not silently emit the wrong math (the old `_ =>` arms mapped any
    // unknown unary to silu and any unknown binary to add).
    for (expr, needle) in [
        (
            Expr::Unary("rsqrt", Box::new(Expr::Lit(Lit::Float(2.0)))),
            "rsqrt",
        ),
        (
            Expr::Binary(
                "div",
                Box::new(Expr::Lit(Lit::Int(1))),
                Box::new(Expr::Lit(Lit::Int(2))),
            ),
            "div",
        ),
    ] {
        let e = Elementwise {
            expr,
            operands: vec![Operand {
                name: "a".into(),
                views: vec![],
            }],
            env: vec![("a".into(), "a".into())],
            out_var: "out".into(),
            out_nullable: true,
        };
        let err = emit(&e).unwrap_err();
        assert!(err.contains(needle), "{err}");
    }
}

#[test]
fn launcher_validates_block_and_never_promises_restrict() {
    let src = emit_term(&leaf_body());
    // block > 1024 is a launch-config error, not a silent clamp
    assert!(src.contains("block > 1024u"), "{src}");
    // the IR carries no alias information — no __restrict__ anywhere
    assert!(!src.contains("__restrict__"), "{src}");
}

fn leaf_body() -> String {
    format!(r#"{{"op":"neg","args":[{}]}}"#, leaf("a"))
}

#[test]
fn declines_qgemv_ops_by_name() {
    // the remaining qgemv-only spellings have no standalone CUDA
    // lowering: dequant/unpack_i4 outside a dot denote materialised
    // tiles, and bare reduce/split/stage with no dot body are not
    // contract terms. `dot` itself now lowers — see contract_test.rs.
    for op in ["dequant", "unpack_i4", "reduce", "split", "stage"] {
        let body = format!(r#"{{"op":"{op}","args":[]}}"#);
        let err = compile(&parse(&elem_term(&body))).unwrap_err();
        assert!(err.contains(op), "{op}: {err}");
    }
}

#[test]
fn declines_views_over_computed_tiles() {
    // transpose(mul(a, b)) — a view of a computed tile has no honest
    // stride-only transcription
    let body = format!(
        r#"{{"op":"transpose","args":[{{"op":"mul","args":[{},{}]}},0,1]}}"#,
        leaf("a"),
        leaf("b")
    );
    let err = compile(&parse(&elem_term(&body))).unwrap_err();
    assert!(err.contains("leaf"), "{err}");
}

