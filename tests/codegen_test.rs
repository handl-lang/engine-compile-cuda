#[test]
fn cli_end_to_end() {
    // the binary reads a term on stdin and writes the .cu on stdout
    let body = format!(
        r#"{{"op":"relu","args":[{{"op":"mul","args":[{},{}]}}]}}"#,
        leaf("a"),
        leaf("b")
    );
    let raw = elem_term(&body);
    let out = std::process::Command::new(env!("CARGO_BIN_EXE_tool-compile-cuda"))
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()
        .and_then(|mut c| {
            use std::io::Write;
            c.stdin.take().unwrap().write_all(raw.as_bytes())?;
            c.wait_with_output()
        })
        .expect("tool-compile-cuda binary runs");
    assert!(out.status.success());
    let src = String::from_utf8(out.stdout).unwrap();
    assert!(src.contains("__global__"));
    // relu lowers to the (x > 0 ? x : 0) select
    assert!(src.contains("(W)0 ?"), "{src}");
}

#[test]
fn emitted_source_compiles_under_nvcc_when_present() {
    // No GPU is required for a syntax/semantic check — only the CUDA
    // toolkit. When nvcc is absent the test skips honestly (returns),
    // matching the family's no-GPU-in-CI contract.
    let Ok(probe) = std::process::Command::new("nvcc").arg("--version").output() else {
        eprintln!("nvcc not found — skipping the compile check");
        return;
    };
    if !probe.status.success() {
        eprintln!("nvcc --version failed — skipping the compile check");
        return;
    }
    let body = format!(
        r#"{{"op":"silu","args":[{{"op":"mul","args":[
            {{"op":"transpose","args":[{},0,1]}}, {}]}}]}}"#,
        leaf("w"),
        leaf("x")
    );
    let src = emit_term(&body);
    let dir = std::env::temp_dir();
    let cu = dir.join(format!("tool_compile_cuda_emit_{}.cu", std::process::id()));
    let obj = dir.join(format!("tool_compile_cuda_emit_{}.o", std::process::id()));
    std::fs::write(&cu, &src).unwrap();
    let status = std::process::Command::new("nvcc")
        .args(["-c", "-o"])
        .arg(&obj)
        .arg(&cu)
        .status()
        .expect("nvcc runs");
    let _ = std::fs::remove_file(&cu);
    let _ = std::fs::remove_file(&obj);
    assert!(status.success(), "nvcc rejected the emitted source");
}
