//! Structural tests for the contract lowering (`dot` / `split` /
//! `reduce` — the qgemv fragment): emitted-source pins only, no GPU.

use compile_cuda::{Node, as_contract, compile, emit_contract};

fn leaf(name: &str) -> String {
    format!(r#"{{"leaf":{{"name":"{name}"}}}}"#)
}

fn kleaf(name: &str) -> String {
    format!(r#"{{"leaf":{{"name":"{name}","kind":"k"}}}}"#)
}

fn gleaf(name: &str, div: i64) -> String {
    format!(r#"{{"leaf":{{"name":"{name}","kind":"g","div":{div}}}}}"#)
}

fn store(body: &str) -> String {
    format!(r#"{{"op":"store","args":[{body},{}]}}"#, leaf("out"))
}

fn parse(raw: &str) -> Node {
    serde_json::from_str(raw).expect("the test term must parse")
}

fn emit_contract_term(body: &str) -> String {
    let c = as_contract(&parse(&store(body))).expect("contract term");
    emit_contract(&c).expect("a recognised contract emits")
}

/// The AWQ qgemv body: dot(dequant(unpack_i4(w, shifts), z, s, g), x)
fn dequant_dot() -> String {
    format!(
        r#"{{"op":"dot","args":[{{"op":"dequant","args":[
            {{"op":"unpack_i4","args":[{},{}]}}, {}, {}, 128]}},{}]}}"#,
        kleaf("w"),
        leaf("shifts"),
        gleaf("z", 128),
        gleaf("s", 128),
        kleaf("x")
    )
}

#[test]
fn plain_dot_lowers_to_a_matvec_kernel() {
    // dot(transpose(w, 0, 1), x) — the weight-first matmul spelling
    let body = format!(
        r#"{{"op":"dot","args":[{{"op":"transpose","args":[{},0,1]}},{}]}}"#,
        leaf("w"),
        kleaf("x")
    );
    let src = emit_contract_term(&body);
    assert!(src.contains("#include <cuda_runtime.h>"));
    assert!(src.contains("template <typename T>"));
    assert!(src.contains("__global__ void contract_kernel_"));
    assert!(src.contains("<<<grid, tb, 0, stream>>>"));
    assert!(src.contains("extern \"C\" cudaError_t launch_contract_"));
    // all six dtype instantiations dispatch
    for case in [
        "CUDA_CONTRACT_F32",
        "CUDA_CONTRACT_F64",
        "CUDA_CONTRACT_F16",
        "CUDA_CONTRACT_BF16",
        "CUDA_CONTRACT_I32",
        "CUDA_CONTRACT_I64",
    ] {
        assert!(src.contains(case), "missing {case}");
    }
    // block > 1024 is a launch-config error, not a silent clamp
    assert!(src.contains("block > 1024u"), "{src}");
    // grid-stride over nout, serial k accumulation in fp32
    assert!(src.contains("i += gstride"));
    assert!(src.contains("i < nout"));
    assert!(src.contains("k < klen0"), "{src}");
    assert!(src.contains("float acc = 0.0f"));
    assert!(src.contains("to_f32"));
    assert!(src.contains("store_cast<T>"));
    // stride-described loads: k*ak + i*an for the tile, k*kx for x
    assert!(src.contains("a0[k*ak0 + i*an0]"), "{src}");
    assert!(src.contains("x0[k*kx0]"), "{src}");
    // the dot's geom block leads with its own klen
    assert!(src.contains("k < klen0"), "{src}");
    assert!(src.contains("geom[1] /* klen0 */"), "{src}");
    assert!(src.contains("geom[4] /* kx0 */"), "{src}");
    // the IR carries no alias information — no __restrict__ anywhere
    assert!(!src.contains("__restrict__"), "{src}");
    // the transpose view is documented, not silently dropped
    assert!(src.contains("transpose(0,1)"));
    // in_ptrs order is documented
    assert!(src.contains("in_ptrs[0] = dot 0 tile \"w\""));
    assert!(src.contains("in_ptrs[1] = dot 0 x \"x\""));
    assert!(src.starts_with("// Generated by compile-cuda"));
}

#[test]
fn split_k_term_lowers_and_checks_the_k_literal() {
    // store(split(512, 4, pipeline(2, dot(a, x))), out) — the split-k
    // spelling. The fused kernel runs the whole k range; the literal
    // becomes a launch-time geom check.
    let body = format!(
        r#"{{"op":"split","args":[512,4,{{"op":"pipeline","args":[2,{{"op":"dot","args":[{},{}]}}]}}]}}"#,
        leaf("a"),
        kleaf("x")
    );
    let src = emit_contract_term(&body);
    assert!(src.contains("contract_kernel_"));
    assert!(
        src.contains("if (geom[1] != 512) return cudaErrorInvalidValue;"),
        "{src}"
    );
    assert!(src.contains("k < klen0"), "{src}");
}

#[test]
fn the_full_qgemv_spelling_lowers() {
    // store(split(k, parts, [pipeline] dot(dequant(unpack_i4(w, shifts),
    // z, s, g), x)), out) — exactly what lib-kernel-ir's qgemv() emits.
    let body = format!(
        r#"{{"op":"split","args":[512,4,{{"op":"pipeline","args":[1,{}]}}]}}"#,
        dequant_dot()
    );
    let src = emit_contract_term(&body);
    // the dequant dot emits the nibble/dequant arithmetic
    assert!(src.contains("& 0xF"), "{src}");
    assert!(src.contains("k / zdiv0"), "{src}");
    assert!(src.contains("k / sdiv0"), "{src}");
    // packed w / shifts / zero z are int operands; s / x are T
    assert!(src.contains("const int* w0"), "{src}");
    assert!(src.contains("const int* sh0"), "{src}");
    assert!(src.contains("const int* z0"), "{src}");
    assert!(src.contains("const T* s0"), "{src}");
    assert!(src.contains("const T* x0"), "{src}");
    // geom carries the ten-stride dequant block
    for s in [
        "wk0", "wn0", "zg0", "zn0", "zdiv0", "sg0", "sn0", "sdiv0", "shs0", "kx0",
    ] {
        assert!(src.contains(s), "missing stride {s}");
    }
    // in_ptrs order: w, shifts, z, s, x
    assert!(src.contains("in_ptrs[0] = dot 0 w \"w\""));
    assert!(src.contains("in_ptrs[1] = dot 0 shifts \"shifts\""));
    assert!(src.contains("in_ptrs[2] = dot 0 z \"z\""));
    assert!(src.contains("in_ptrs[3] = dot 0 s \"s\""));
    assert!(src.contains("in_ptrs[4] = dot 0 x \"x\""));
    // the k literal is still checked
    assert!(src.contains("if (geom[1] != 512)"), "{src}");
}

#[test]
fn reduce_of_dot_partials_sums_into_one_kernel() {
    // store(bias(reduce(stage(dot a x), pipeline(3, dot b y)), bias), out)
    let plain = format!(r#"{{"op":"dot","args":[{},{}]}}"#, leaf("a"), kleaf("x"));
    let staged = format!(r#"{{"op":"stage","args":[{plain}]}}"#);
    let piped = format!(
        r#"{{"op":"pipeline","args":[3,{{"op":"dot","args":[{},{}]}}]}}"#,
        leaf("b"),
        kleaf("y")
    );
    let body = format!(r#"{{"op":"reduce","args":[{staged},{piped}]}}"#);
    let body = format!(r#"{{"op":"bias","args":[{},{}]}}"#, body, leaf("bias"));
    let src = emit_contract_term(&body);
    // two plain dots plus one bias operand
    assert!(src.contains("a0[k*ak0 + i*an0]"), "{src}");
    assert!(src.contains("a1[k*ak1 + i*an1]"), "{src}");
    assert!(src.contains("b0[i*bs0]"), "{src}");
    assert!(src.contains("in_ptrs[4] = bias 0 \"bias\""));
    assert_eq!(src.matches("float acc = 0.0f").count(), 1);
    // each dot's geom block leads with its own klen — dots in a
    // reduce may contract different k axes (dot1 block: klen1,ak1,
    // an1,kx1 at geom[5..9), bias bs0 at geom[9])
    assert!(src.contains("k < klen0"), "{src}");
    assert!(src.contains("k < klen1"), "{src}");
    assert!(src.contains("geom[5] /* klen1 */"), "{src}");
    assert!(src.contains("geom[8] /* kx1 */"), "{src}");
    assert!(src.contains("geom[9] /* bs0 */"), "{src}");
}

#[test]
fn mixed_plain_and_dequant_dots_compose() {
    let plain = format!(r#"{{"op":"dot","args":[{},{}]}}"#, leaf("a"), kleaf("x"));
    let body = format!(r#"{{"op":"reduce","args":[{plain},{}]}}"#, dequant_dot());
    let src = emit_contract_term(&body);
    assert!(src.contains("a0[k*ak0 + i*an0]"), "{src}");
    assert!(src.contains("& 0xF"), "{src}");
    // geom: 3 plain strides then 10 dequant strides
    assert!(src.contains("geom[4] /* kx0 */"), "{src}");
    assert!(src.contains("geom[6] /* wk1 */"), "{src}");
    assert!(src.contains("geom[15] /* kx1 */"), "{src}");
}

#[test]
fn declines_non_dot_contract_bodies_by_name() {
    // dot over a computed tile — the tile would need materialisation
    let bad_lhs = format!(
        r#"{{"op":"dot","args":[{{"op":"mul","args":[{},{}]}},{}]}}"#,
        leaf("a"),
        leaf("b"),
        kleaf("x")
    );
    let err = compile(&parse(&store(&bad_lhs))).unwrap_err();
    assert!(err.contains("leaf"), "{err}");

    // reduce over an elementwise partial — not a dot
    let bad_partial = format!(
        r#"{{"op":"reduce","args":[{{"op":"mul","args":[{},{}]}}]}}"#,
        leaf("a"),
        leaf("b")
    );
    let err = compile(&parse(&store(&bad_partial))).unwrap_err();
    assert!(err.contains("partial must be a dot"), "{err}");

    // split of an elementwise body — a k-axis reduction whose k axis
    // cannot be identified from the term alone
    let bad_split = format!(
        r#"{{"op":"split","args":[8,2,{{"op":"mul","args":[{},{}]}}]}}"#,
        leaf("a"),
        leaf("b")
    );
    let err = compile(&parse(&store(&bad_split))).unwrap_err();
    assert!(err.contains("dot"), "{err}");

    // dequant whose zero leaf is not group-indexed
    let bad_g = format!(
        r#"{{"op":"dot","args":[{{"op":"dequant","args":[
            {{"op":"unpack_i4","args":[{},{}]}}, {}, {}, 128]}},{}]}}"#,
        kleaf("w"),
        leaf("shifts"),
        kleaf("z"), // kind "k", not "g"
        gleaf("s", 128),
        kleaf("x")
    );
    let err = compile(&parse(&store(&bad_g))).unwrap_err();
    assert!(err.contains("kind \"g\""), "{err}");

    // dequant over a non-unpack_i4 q
    let bad_q = format!(
        r#"{{"op":"dot","args":[{{"op":"dequant","args":[{}, {}, {}, 128]}},{}]}}"#,
        leaf("q"),
        gleaf("z", 128),
        gleaf("s", 128),
        kleaf("x")
    );
    let err = compile(&parse(&store(&bad_q))).unwrap_err();
    assert!(err.contains("unpack_i4"), "{err}");
}

#[test]
fn elementwise_terms_still_take_the_elementwise_path() {
    // a store(mul...) term never reaches the contract path
    let body = format!(r#"{{"op":"mul","args":[{},{}]}}"#, leaf("a"), leaf("b"));
    let node = parse(&store(&body));
    let e = compile_cuda::as_elementwise(&node).expect("elementwise");
    let src = compile_cuda::emit(&e).expect("elementwise emits");
    assert!(src.contains("elem_kernel_"), "{src}");
    assert!(!src.contains("contract_kernel_"));
}

#[test]
fn contract_kernel_and_launcher_names_are_stable_and_distinct() {
    let b1 = format!(r#"{{"op":"dot","args":[{},{}]}}"#, leaf("a"), kleaf("x"));
    let b2 = format!(r#"{{"op":"dot","args":[{},{}]}}"#, leaf("b"), kleaf("x"));
    let s1 = emit_contract_term(&b1);
    let s2 = emit_contract_term(&b2);
    let name1 = s1
        .lines()
        .find(|l| l.starts_with("extern \"C\" cudaError_t launch_contract_"))
        .unwrap();
    let name2 = s2
        .lines()
        .find(|l| l.starts_with("extern \"C\" cudaError_t launch_contract_"))
        .unwrap();
    assert_ne!(name1, name2);
    // determinism
    assert_eq!(name1, {
        let s = emit_contract_term(&b1);
        s.lines()
            .find(|l| l.starts_with("extern \"C\" cudaError_t launch_contract_"))
            .unwrap()
            .to_string()
    });
}

#[test]
fn emitted_contract_source_compiles_under_nvcc_when_present() {
    // Same honest skip as the elementwise check: nvcc absent -> return.
    let Ok(probe) = std::process::Command::new("nvcc").arg("--version").output() else {
        eprintln!("nvcc not found — skipping the compile check");
        return;
    };
    if !probe.status.success() {
        eprintln!("nvcc --version failed — skipping the compile check");
        return;
    }
    let body = format!(
        r#"{{"op":"split","args":[64,2,{{"op":"dot","args":[{},{}]}}]}}"#,
        leaf("a"),
        kleaf("x")
    );
    let src = emit_contract_term(&body);
    let dir = std::env::temp_dir();
    let cu = dir.join(format!("compile_cuda_contract_{}.cu", std::process::id()));
    let obj = dir.join(format!("compile_cuda_contract_{}.o", std::process::id()));
    std::fs::write(&cu, &src).unwrap();
    let status = std::process::Command::new("nvcc")
        .args(["-c", "-o"])
        .arg(&obj)
        .arg(&cu)
        .status()
        .expect("nvcc runs");
    let _ = std::fs::remove_file(&cu);
    let _ = std::fs::remove_file(&obj);
    assert!(status.success(), "nvcc rejected the emitted source");
}
